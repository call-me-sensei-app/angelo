"""The table of Blender Python names Blender renamed or removed since 3.6 (``assets/api_drift.json``).

One table for every place Angelo states such a name: Blender's own error (``bpy_angelo_renamed_api.cc``, rendered
from the same file), the refusal before a script runs (``script_api_removed``) and the note after it ran
(``script_api_notes``). It is generated by ``scripts/angelo/api_drift`` from API dumps of every release since 3.6,
Blender's file-versioning renames and a short cited overlay; doc/angelo/agent_execution.rst, "Removed Blender API".

Each entry: ``use`` (``attribute``, ``enum_item``, ``socket``, ``operator``, ``operator_argument``,
``module_member``), ``owner`` (struct, node idname, operator or module), ``property`` (an enum's property, a
socket's ``inputs``/``outputs``), ``name``, ``replacements``, ``hint`` (the error's sentence), ``since``, ``source``
or ``evidence``, ``elsewhere`` (an attribute name some other type still has), ``certain``, and for certain rows
``refusal`` and ``note``. The refusal and the note use certain rows only; the error uses every row.

Read once, on first use: importing this module reads nothing.
"""

import functools
import json
import os

TABLE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "assets", "api_drift.json")


@functools.lru_cache(maxsize=1)
def entries():
    """Every entry, in the table's order."""
    with open(TABLE_PATH, encoding="utf-8") as handle:
        return tuple(json.load(handle)["entries"])


def certain(field):
    """The certain entries that carry ``field`` (``refusal`` or ``note``)."""
    return tuple(entry for entry in entries() if entry.get("certain") and entry.get(field))
