"""A network fence around this test process and a TLS stand-in for the Teams host list. Host tests only.

``Fence`` replaces name resolution and connects for the whole process while it is installed:

* every hostname looked up (``socket.getaddrinfo``, ``gethostbyname``, ``gethostbyname_ex``, or a name handed to
  ``socket.connect`` itself, which C resolves without Python's ``getaddrinfo``) is recorded;
* a name on the published list (``published``) resolves to ``STAND_IN``, and every connect to ``STAND_IN`` is
  redirected to the loopback stand-in server, so nothing leaves this computer;
* any other name fails with ``socket.gaierror`` and is recorded as refused;
* a connect to an address no name on the list resolved to (a literal IP, a proxy's address) is refused and recorded
  in ``blocked``; loopback connects (the fake console, the refusing proxy) pass.

``STAND_IN`` must look public (``ipaddress.is_global``) because Media Studio's transport refuses private addresses
(``studio_http.public_addresses``). It is the deprecated 6to4 relay anycast address, and the fence redirects every
connect to it, so no packet is ever sent there.

``StandIn`` is one threaded HTTPS server on 127.0.0.1 whose certificate's SANs cover every published name (one
self-signed root generated by ``certificate``; nothing trusts it unless the test's policy adds it). It dispatches
each request to ``answer(request)`` by its ``Host`` header and path. ``forward`` passes a request on to an
in-process plain-HTTP server such as ``fake_team_console``.

The fence is general: it never lists a test's hosts. Only the published names are admitted; whatever else a flow
looks up is refused, and the test decides what refusals it expects.
"""

import _socket
import errno
import http.client
import ipaddress
import shutil
import socket
import ssl
import subprocess
import threading
import unittest
import urllib.request
from dataclasses import dataclass
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from unittest import mock
from urllib.parse import urlsplit

from host_test_policy import environment_skip

# The published list for a Teams gateway profile (doc/angelo/enterprise_policy.rst, "Network").
PUBLISHED_HOSTS = frozenset({"gateway.angelo.studio", "console.angelo.studio", "angelo.studio",
                             "downloads.angelo.studio", "assets.toonlab.io", "cdn.toonlab.io"})
R2_SUFFIX = ".r2.cloudflarestorage.com"   # Angelo's R2 download host: any account's endpoint under it.
STAND_IN = "192.88.99.1"
LOOPBACK_NAMES = frozenset({"localhost"})


def normal(name):
    return name.decode("ascii", "replace") if isinstance(name, bytes) else str(name)


def published(host):
    """Whether ``host`` is on the published Teams list."""
    host = normal(host).lower().rstrip(".")
    return host in PUBLISHED_HOSTS or host.endswith(R2_SUFFIX)


def _literal(host):
    """The IP address ``host`` spells, or None for a name."""
    text = normal(host).strip("[]").split("%", 1)[0]
    try:
        return ipaddress.ip_address(text)
    except ValueError:
        return None


def _port(port):
    if port is None:
        return 0
    if isinstance(port, int):
        return port
    text = normal(port)
    if text.isdigit():
        return int(text)
    return {"https": 443, "http": 80}.get(text, 0)


def certificate(folder):
    """``(certificate, key)`` paths: a self-signed root whose SANs are the published names and the R2 wildcard."""
    openssl = shutil.which("openssl")
    if not openssl:
        raise unittest.SkipTest(environment_skip("openssl is not installed"))
    folder = Path(folder)
    cert, key, config = folder / "hosts-root.pem", folder / "hosts-key.pem", folder / "openssl.cnf"
    names = ",".join("DNS:" + name for name in sorted(PUBLISHED_HOSTS) + ["*" + R2_SUFFIX])
    config.write_text("[req]\ndistinguished_name=dn\nx509_extensions=extensions\nprompt=no\n"
                      "[dn]\nCN=Angelo host fence test root\n"
                      "[extensions]\nbasicConstraints=critical,CA:TRUE\nsubjectKeyIdentifier=hash\n"
                      "subjectAltName=%s\n" % names, encoding="utf-8")
    subprocess.run([openssl, "req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "2", "-config", str(config),
                    "-keyout", str(key), "-out", str(cert)], check=True, capture_output=True, timeout=60)
    return str(cert), str(key)


class Fence:
    """Records and fences every lookup and connect of this process (module docstring)."""

    def __init__(self, port):
        self.port = port
        self._lock = threading.Lock()
        self.reset()

    def reset(self):
        with self._lock:
            self.looked_up, self.refused, self.blocked = [], [], []

    def names(self):
        with self._lock:
            return set(self.looked_up)

    def refusals(self):
        with self._lock:
            return list(self.refused)

    def blocked_connects(self):
        with self._lock:
            return list(self.blocked)

    def install(self, case):
        """Patch the process for ``case`` (a TestCase); its cleanups take every patch out again.

        The machine's own proxy settings (macOS network settings, the Windows registry) are outside this test:
        ``urllib`` reads only the environment, which the test clears, so a proxy configured on the developer's
        computer can't turn into a refusal here. A proxy that is set in the environment is fenced like any host.
        """
        self._getaddrinfo, self._byname, self._byname_ex = (socket.getaddrinfo, socket.gethostbyname,
                                                           socket.gethostbyname_ex)
        fence = self

        def connect(sock, address):
            return _socket.socket.connect(sock, fence._route(sock, address))

        def connect_ex(sock, address):
            try:
                address = fence._route(sock, address)
            except socket.gaierror:
                return errno.EHOSTUNREACH
            except ConnectionRefusedError:
                return errno.ECONNREFUSED
            return _socket.socket.connect_ex(sock, address)

        patches = [mock.patch.object(socket, "getaddrinfo", self.getaddrinfo),
                   mock.patch.object(socket, "gethostbyname", self.gethostbyname),
                   mock.patch.object(socket, "gethostbyname_ex", self.gethostbyname_ex),
                   mock.patch.object(socket.socket, "connect", connect),
                   mock.patch.object(socket.socket, "connect_ex", connect_ex),
                   mock.patch.object(urllib.request, "getproxies", urllib.request.getproxies_environment)]
        for patch in patches:
            patch.start()
            case.addCleanup(patch.stop)

    # Resolution ---------------------------------------------------------------------------------------------------

    def _name(self, host):
        """Record a looked-up name; True when it is on the list, else it is refused (``socket.gaierror``)."""
        name = normal(host).lower().rstrip(".")
        with self._lock:
            self.looked_up.append(name)
            if not published(name):
                self.refused.append(name)
                raise socket.gaierror(socket.EAI_NONAME, "Not on the published Teams host list: " + name)
        return True

    def _passes(self, host):
        """Whether ``host`` resolves without the fence: none, a literal address or a loopback name."""
        return not host or _literal(host) is not None or normal(host).lower() in LOOPBACK_NAMES

    def getaddrinfo(self, host, port, family=0, type=0, proto=0, flags=0):
        if self._passes(host):
            return self._getaddrinfo(host, port, family, type, proto, flags)
        self._name(host)
        return [(socket.AF_INET, type or socket.SOCK_STREAM, proto or socket.IPPROTO_TCP, "", (STAND_IN, _port(port)))]

    def gethostbyname(self, host):
        if self._passes(host):
            return self._byname(host)
        self._name(host)
        return STAND_IN

    def gethostbyname_ex(self, host):
        if self._passes(host):
            return self._byname_ex(host)
        self._name(host)
        return normal(host), [], [STAND_IN]

    # Connects -----------------------------------------------------------------------------------------------------

    def _route(self, sock, address):
        """Where a connect to ``address`` really goes: the stand-in server, loopback as asked, or nowhere."""
        if sock.family not in (socket.AF_INET, socket.AF_INET6) or not isinstance(address, tuple):
            return address
        host, port = address[0], address[1]
        literal = _literal(host)
        if literal is None:   # A name given to connect itself: C would resolve it without getaddrinfo.
            if normal(host).lower() in LOOPBACK_NAMES:
                return address
            self._name(host)
            literal = ipaddress.ip_address(STAND_IN)
        mapped = getattr(literal, "ipv4_mapped", None) or literal
        if str(mapped) == STAND_IN:
            return ("127.0.0.1", self.port) if sock.family == socket.AF_INET else ("::ffff:127.0.0.1", self.port, 0, 0)
        if literal.is_loopback or mapped.is_loopback:
            return address
        with self._lock:
            self.blocked.append("%s:%s" % (literal, port))
        raise ConnectionRefusedError(errno.ECONNREFUSED, "Connect to an address no published name resolved to: %s"
                                     % literal)


# The stand-in server -----------------------------------------------------------------------------------------------

@dataclass
class Request:
    host: str
    method: str
    path: str
    query: str
    headers: dict
    body: bytes

    def target(self):
        return self.path + ("?" + self.query if self.query else "")


def forward(port, request):
    """``(status, headers, body)`` of ``request`` passed on to the plain-HTTP server on 127.0.0.1:``port``."""
    skipped = {"host", "connection", "content-length", "accept-encoding", "transfer-encoding"}
    connection = http.client.HTTPConnection("127.0.0.1", port, timeout=30)
    try:
        connection.request(request.method, request.target(), body=request.body or None,
                           headers={k: v for k, v in request.headers.items() if k.lower() not in skipped})
        response = connection.getresponse()
        data = response.read()
        kept = {k: v for k, v in response.getheaders()
                if k.lower() not in skipped | {"content-length", "server", "date"}}
        return response.status, kept, data
    finally:
        connection.close()


class _Server(ThreadingHTTPServer):
    daemon_threads = True

    def finish_request(self, request, client_address):
        """The TLS handshake runs on the request's own thread, so a client that never finishes it blocks nobody."""
        request.settimeout(30)
        try:
            secure = self.context.wrap_socket(request, server_side=True)
        except (ssl.SSLError, OSError) as error:
            self.owner.handshake_failed(error)
            return
        try:
            self.RequestHandlerClass(secure, client_address, self)
        finally:
            secure.close()


class StandIn:
    """The HTTPS stand-in for every published host (module docstring). ``answer(request)`` returns
    ``(status, headers, body)``; every request is recorded in ``served`` and every exception in ``errors``."""

    def __init__(self, cert, key):
        self.answer = None
        self.served, self.errors, self.handshakes_failed = [], [], []
        self._lock = threading.Lock()
        owner = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def _serve(self):
                length = int(self.headers.get("Content-Length") or 0)
                body = self.rfile.read(length) if length else b""
                parts = urlsplit(self.path)
                host = (self.headers.get("Host") or "").split(":", 1)[0].lower()
                request = Request(host, self.command, parts.path, parts.query, dict(self.headers), body)
                with owner._lock:
                    owner.served.append((host, self.command, parts.path))
                try:
                    status, headers, data = owner.answer(request)
                except Exception as error:  # noqa: BLE001 - reported to the test, answered as a server error.
                    with owner._lock:
                        owner.errors.append("%s %s%s: %r" % (self.command, host, parts.path, error))
                    status, headers, data = 500, {}, b""
                self.send_response(status)
                for name, value in headers.items():
                    self.send_header(name, value)
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                if self.command != "HEAD":
                    self.wfile.write(data)

            do_GET = do_POST = do_PUT = do_DELETE = do_HEAD = _serve  # noqa: N815

        context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        context.load_cert_chain(cert, key)
        self.server = _Server(("127.0.0.1", 0), Handler)
        self.server.context, self.server.owner = context, self
        self.port = self.server.server_address[1]
        self.thread = threading.Thread(target=self.server.serve_forever, kwargs={"poll_interval": 0.05}, daemon=True)
        self.thread.start()

    def handshake_failed(self, error):
        with self._lock:
            self.handshakes_failed.append(repr(error))

    def reset(self):
        with self._lock:
            self.served, self.errors, self.handshakes_failed = [], [], []

    def hosts(self):
        with self._lock:
            return {host for host, _method, _path in self.served}

    def close(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(10)
