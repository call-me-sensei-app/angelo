def samples():
    folder = OUT / 'generated'
    command = [bpy.app.binary_path, '--background', '--factory-startup', '--disable-autoexec', '--python-exit-code', '1',
               '--python', str(Path(__file__).with_name('fab_formats_samples.py')), '--', str(folder)]
    done = subprocess.run(command, capture_output=True, text=True, timeout=300)
    (OUT / 'samples.log').write_text(done.stdout + done.stderr)
    assert done.returncode == 0, 'The sample writer failed; see samples.log'
    rows = [dict(row, source='generated') for row in json.loads((folder / 'samples.json').read_text())]
    extra = os.environ.get('ANGELO_QA_FAB_SAMPLES')
    if extra:
        rows += [dict(row, source='fab') for row in json.loads(Path(extra).read_text())]
    return rows


def view3d():
    window = bpy.context.window
    area = next(a for a in window.screen.areas if a.type == 'VIEW_3D')
    return window, area, next(r for r in area.regions if r.type == 'WINDOW')


def prepare(sample, folder):
    """Worker-thread part of Session.prepare after the download: content check, conversion (or the GLB itself)."""
    path = Path(sample['path'])
    fmt = fab_formats.BY_CODE[sample['format']]
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    folder.mkdir(parents=True, exist_ok=True)
    download = folder / 'download.bin'
    if not download.exists():
        download.write_bytes(path.read_bytes())
    facts = fab_cache._inspect(download, fmt)
    item = SimpleNamespace(identity='12345678-1234-1234-1234-%012d' % (abs(hash(sample['title'])) % 10 ** 12),
                           title=sample['title'], license='Fab Standard', author='Fixture')
    if fmt.direct:
        return item, PayloadProof(download, download.stat().st_size, digest), facts
    converted, size, sealed, result = fab_convert.cached(folder, download, digest, fmt, facts, item, lambda: None)
    return item, PayloadProof(converted, size, sealed, 'asset.blend'), dict(facts, conversion=result)


def run_worker(work):
    """Run ``work`` on a thread; measure the longest gap between main-thread ticks meanwhile (responsiveness)."""
    box, gaps, last = {}, [], [time.monotonic()]

    def target():
        try:
            box['value'] = work()
        except BaseException as error:   # noqa: BLE001 - re-raised on the main thread.
            box['error'] = error
    thread = threading.Thread(target=target, daemon=True)
    thread.start()
    while thread.is_alive():
        yield None
        now = time.monotonic()
        gaps.append(now - last[0])
        last[0] = now
    if 'error' in box:
        raise box['error']
    return box['value'], max(gaps, default=0.0)


def _upstream(socket, seen):
    """Image texture nodes upstream of ``socket``, through any chain of nodes."""
    found = set()
    for link in socket.links:
        node = link.from_node
        if node.name in seen:
            continue
        seen.add(node.name)
        if node.type == 'TEX_IMAGE':
            found.add(node.name)
        for socket_in in node.inputs:
            if socket_in.is_linked:
                found |= _upstream(socket_in, seen)
    return found


def _sockets(material):
    tree = material.node_tree
    shader = next(n for n in tree.nodes if n.type == 'BSDF_PRINCIPLED')
    output = next(n for n in tree.nodes if n.type == 'OUTPUT_MATERIAL' and n.is_active_output)
    named = {name: shader.inputs[name] for name in ('Base Color', 'Normal', 'Roughness', 'Metallic', 'Alpha')}
    named['Displacement'] = output.inputs['Displacement']
    return tree, output, named


def textures_feeding(material):
    """``(every image texture node, the ones that reach the active output)`` in ``material``."""
    tree, output, _named = _sockets(material)
    maps = {n.name for n in tree.nodes if n.type == 'TEX_IMAGE' and n.image is not None}
    fed = set()
    for socket in output.inputs:
        if socket.is_linked:
            fed |= _upstream(socket, set())
    return maps, fed


def wired_inputs(material):
    """The shader inputs (and the output's Displacement) an image texture feeds."""
    _tree, _output, named = _sockets(material)
    return {name for name, socket in named.items() if socket.is_linked and _upstream(socket, set())}


def stats():
    images = [i for i in bpy.data.images if i.source in ('FILE', 'TILED')]
    return {'objects': len(bpy.data.objects), 'texts': len(bpy.data.texts), 'materials': len(bpy.data.materials),
            'unpacked_images': [i.name for i in images if i.packed_file is None],
            'python_drivers': sum(needs_python(c.driver) for o in bpy.data.objects
                                  if o.animation_data for c in o.animation_data.drivers),
            'simple_drivers': sum(not needs_python(c.driver) for o in bpy.data.objects
                                  if o.animation_data for c in o.animation_data.drivers)}


def refuse(sample, index):
    """A hostile sample: refused with the network sentence before the child opens anything; the scene unchanged."""
    before = stats()
    try:
        yield from run_worker(lambda: prepare(sample, OUT / 'cache' / ('%02d' % index)))
    except fab_convert.ConvertRefused as refusal:
        message = str(refusal)
    else:
        raise AssertionError('A hostile sample was converted: %s' % sample['title'])
    assert message in (fab_convert.NETWORK, fab_convert.MESSAGES['OUTSIDE_REFERENCE']), message
    assert stats() == before
    report['refusals']['%s:%s' % (sample['source'], sample['title'])] = message


def add(sample, index):
    if sample.get('refused'):
        yield from refuse(sample, index)
        return
    fmt = fab_formats.BY_CODE[sample['format']]
    key = '%s:%s' % (sample['source'], sample['title'])
    folder = OUT / 'cache' / ('%02d' % index)
    window, area, region = view3d()
    targets = ()
    if fmt.kind == 'material':
        bpy.ops.object.select_all(action='DESELECT')
        cube = bpy.data.objects.get('Surface target')
        # A generated sample says where it goes ('apply'); between them they cover both. Real downloads alternate
        # among themselves, the first on the selected cube, so one real set also proves the applied path.
        apply = sample.get('apply')
        if apply is None:
            report['real_surfaces'] = report.get('real_surfaces', 0) + 1
            apply = report['real_surfaces'] % 2 == 1
        if cube is not None and apply:
            cube.select_set(True)
            window.view_layer.objects.active = cube
            targets = (cube,)
    before = stats()
    t0 = time.monotonic()
    (item, proof, facts), worst_gap = yield from run_worker(lambda: prepare(sample, folder))
    prepared_at = time.monotonic()
    row = fab_native_job._row(SimpleNamespace(item=item, payload_proof=proof, facts=facts))
    payload = AssetCommit(row, deadline=time.monotonic() + 600, payload_format=fab_native_job.payload_format(row))
    yield from run_worker(lambda: payload.seal_payload(row, threading.Event()))
    sealed_at = time.monotonic()
    with bpy.context.temp_override(window=window, area=area, region=region):
        result = payload.finish(bpy.context, row, targets=targets,
                                format_result=lambda f: fab_native_job._result(f, row, targets))
    visible_at = time.monotonic()
    after = stats()
    assert result['success'] is True and result['kind'] == fmt.kind, result
    assert not after['unpacked_images'], after['unpacked_images']
    assert after['texts'] == before['texts'] and after['python_drivers'] == before['python_drivers'], after
    if fmt.kind == 'model':
        names = [o['name'] for o in result['objects']]
        assert names and all(bpy.data.objects[n].visible_get() for n in names), names
        assert not any(bpy.data.objects[n].type == 'CAMERA' for n in names)
    elif targets:
        assert targets[0].active_material.name == row['datablock'], targets[0].active_material
        if sample.get('channels'):   # Every channel of the set is classified and feeds the shader or the output.
            conversion = facts.get('conversion', {})
            roles = conversion.get('surface', {}).get('roles', [])
            assert sorted(roles) == sorted(sample['channels']), (roles, sample['channels'])
            maps, fed = textures_feeding(targets[0].active_material)
            assert len(maps) == len(sample['channels']) and maps == fed, (sorted(maps), sorted(fed))
            assert {'Base Color', 'Normal', 'Roughness', 'Metallic', 'Alpha', 'Displacement'} <= wired_inputs(
                targets[0].active_material), wired_inputs(targets[0].active_material)
    else:
        material = bpy.data.materials[row['datablock']]
        assert material.asset_data is not None and material.use_fake_user
    conversion = facts.get('conversion', {})
    if sample.get('udim'):   # Every tile of its UDIM set inside the download is packed (re-review r5).
        tiled = [n.image for o in result['objects'] for slot in bpy.data.objects[o['name']].material_slots
                 if slot.material and slot.material.node_tree for n in slot.material.node_tree.nodes
                 if n.type == 'TEX_IMAGE' and n.image is not None and n.image.source == 'TILED']
        assert tiled and all(len(i.tiles) >= 2 and len(i.packed_files) == len(i.tiles) for i in tiled), \
            [(i.name, len(i.tiles), len(i.packed_files)) for i in tiled]
        assert conversion.get('trimmed_tiles', 0) == sample.get('trimmed', 0), conversion
    if sample.get('generated_pattern'):   # Packed bytes on a generated image: removed, the pattern kept (r8).
        grids = [n.image for o in result['objects'] for slot in bpy.data.objects[o['name']].material_slots
                 if slot.material and slot.material.node_tree for n in slot.material.node_tree.nodes
                 if n.type == 'TEX_IMAGE' and n.image is not None]
        assert grids and all(i.source == 'GENERATED' and not len(i.packed_files) and i.generated_type == 'COLOR_GRID'
                             for i in grids), [(i.source, len(i.packed_files), i.generated_type) for i in grids]
    if sample.get('single_view'):   # A packed multiview texture arrives as one plain packed view (re-review r5).
        views = [n.image for o in result['objects'] for slot in bpy.data.objects[o['name']].material_slots
                 if slot.material and slot.material.node_tree for n in slot.material.node_tree.nodes
                 if n.type == 'TEX_IMAGE' and n.image is not None]
        assert views and all(i.packed_file is not None and not i.is_multiview for i in views), views
        assert conversion.get('single_view_images') == 1, conversion
        assert all(i.alpha_mode == 'CHANNEL_PACKED' for i in views), [i.alpha_mode for i in views]
    if sample.get('embedded'):   # Its texture's bytes came from the download: kept and packed, whatever path it names.
        images = [n.image for o in result['objects'] for slot in bpy.data.objects[o['name']].material_slots
                  if slot.material and slot.material.node_tree for n in slot.material.node_tree.nodes
                  if n.type == 'TEX_IMAGE' and n.image is not None]
        assert images and all(i.packed_file is not None for i in images), images
        assert conversion.get('outside_removed', 0) == 0, conversion
    shot = OUT / ('%02d-%s.png' % (index, sample['format']))
    yield None
    # Frame what this add made (its objects, or the meshes its material went on) in Material Preview, so the picture
    # shows its textures; earlier adds stay in the scene beside it.
    shown = [bpy.data.objects[o['name']] for o in result['objects'] if o['name'] in bpy.data.objects]
    # Earlier adds stay in the scene, and the generated samples are all the same cube at the origin: hide the rest
    # for the picture, or an earlier cube drawn in the same place can stand in for this one.
    others = [o for o in window.view_layer.objects if o not in shown and o.visible_get()] if shown else []
    for obj in others:
        obj.hide_set(True)
    bpy.ops.object.select_all(action='DESELECT')
    for obj in shown:
        obj.select_set(True)
    area.spaces.active.shading.type = 'MATERIAL'
    with bpy.context.temp_override(window=window, area=area, region=region):
        if shown:
            window.view_layer.objects.active = shown[0]
            bpy.ops.view3d.view_selected()
            bpy.ops.view3d.zoom(delta=-2)   # A little room around it.
        else:
            bpy.ops.view3d.view_all(center=False)
    for _frame in range(30):   # Material Preview compiles shaders over several redraws.
        yield None
    with bpy.context.temp_override(window=window):
        bpy.ops.screen.screenshot(filepath=str(shot))
    report['screenshots'].append(str(shot))
    for obj in others:
        obj.hide_set(False)
    with bpy.context.temp_override(window=window, area=area, region=region):
        bpy.ops.ed.undo()
    yield None
    undone = stats()
    assert undone['objects'] == before['objects'] and undone['materials'] <= before['materials'], (undone, before)
    with bpy.context.temp_override(window=window, area=area, region=region):
        bpy.ops.ed.redo()
    yield None
    t1 = time.monotonic()
    (_item, _proof, again), _gap = yield from run_worker(lambda: prepare(sample, folder))
    repeat_prepare = time.monotonic() - t1
    report['imports'][key] = {
        'format': sample['format'], 'source': sample['source'], 'bytes': Path(sample['path']).stat().st_size,
        'kind': fmt.kind, 'usage': result.get('usage'), 'objects': result['object_count'],
        'prepare_seconds': round(prepared_at - t0, 3), 'seal_seconds': round(sealed_at - prepared_at, 3),
        'append_seconds_main_thread': round(visible_at - sealed_at, 3),
        'file_to_visible_seconds': round(visible_at - t0, 3), 'worst_main_thread_gap_seconds': round(worst_gap, 3),
        'repeat_prepare_seconds': round(repeat_prepare, 3),
        'repeat_reused_conversion': bool(again.get('conversion', {}).get('reused')) if not fmt.direct else None,
        'conversion': conversion, 'undo_restored': True, 'scaled_to_scene': result.get('scaled_to_scene')}
    assert fmt.direct or report['imports'][key]['repeat_reused_conversion'], 'The repeated add converted again'


def scenario():
    fab_convert.set_binary(bpy.app.binary_path)   # As fab_convert.register does, on the main thread.
    # A mesh with UVs for the texture sets to go on, away from where models stand (Blender's own primitive).
    window, area, region = view3d()
    with bpy.context.temp_override(window=window, area=area, region=region):
        bpy.ops.mesh.primitive_cube_add(size=1.0, location=(0.0, -4.0, 0.5))
    bpy.context.active_object.name = 'Surface target'
    yield None
    report['phase'] = 'samples'
    rows = samples()
    report['samples'] = [{k: v for k, v in r.items() if k != 'path'} for r in rows]
    report['phase'] = 'imports'
    for index, sample in enumerate(rows):
        yield from add(sample, index)
    assert len(report['refusals']) == sum(1 for row in rows if row.get('refused')) >= 2, report['refusals']
    formats = {r['format'] for r in report['imports'].values()}
    assert {'fbx', 'obj', 'gltf', 'usd', 'surface', 'blend'} <= formats, formats
    usages = {r['usage'] for r in report['imports'].values() if r['kind'] == 'material'}
    assert usages == {'applied_material', 'material_in_library'}, usages
    # The generated samples alone cover both, so no machine needs real Fab downloads for either path.
    generated = {r['usage'] for r in report['imports'].values()
                 if r['kind'] == 'material' and r['source'] == 'generated'}
    assert generated == {'applied_material', 'material_in_library'}, generated
    report['checks']['generated_texture_sets_cover_both_usages'] = True
    blend = next(r for r in report['imports'].values() if r['format'] == 'blend' and r['source'] == 'generated')
    # Its Python driver is removed; its Text block is never appended at all (nothing references it), and every
    # import already asserted that no Text block reached the scene.
    assert blend['conversion']['drivers_removed'] >= 1, blend
    report['checks']['generated_blend_scrubbed'] = True
    rug = report['imports'].get('fab:Historic Bazaar Rug (FBX low)')
    if rug is not None:   # A model's baked, padded normal map is found by its name (fab_surface.NAMED_NORMAL_SCORE).
        assert 'normal' in rug['conversion'].get('surface', {}).get('roles', []), rug['conversion']


steps = scenario()
state = {'pending': None}


def tick():
    try:
        assert time.monotonic() - started < 900, 'Fab formats fixture timed out'
        next(steps)
        return 0.02
    except StopIteration:
        report.update(success=True, phase='complete')
    except Exception:
        report.update(phase='failed', error=traceback.format_exc())
        traceback.print_exc()
    (OUT / 'fab-formats.json').write_text(json.dumps(report, indent=2, default=str))
    print('FAB_FORMATS_RESULT', json.dumps({k: report[k] for k in ('success', 'phase')}), flush=True)
    bpy.ops.wm.quit_blender()
    return None


bpy.app.timers.register(qa_boot.gated(tick), first_interval=2, persistent=True)   # After Angelo's start-up.
