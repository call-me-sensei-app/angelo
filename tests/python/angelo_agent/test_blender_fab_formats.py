"""Every Fab format through the app's own path after a download: cache, sandboxed converter, native append, Undo.

Runs in the compiled app's default window (Director Mode, chat open). For each sample the fixture does what
``fab_provider.Session.prepare`` and ``fab_native_job`` do after Fab hands over the file: content check and
conversion on a worker thread (the real ``fab_convert`` child: a background Angelo under its sandbox) while the
main thread keeps ticking, then the native asset transaction appends the clean .blend in the 3D View. It asserts the
scene state (new objects, every texture packed, no Text block, no driver that needs Python, a texture set's material
on the selected cube or in the file's asset library), one Undo removes the import, a repeated add reuses the cached
conversion, and it records times and a screenshot per format.

Samples: generated by ``fab_formats_samples.py`` in a background Angelo (always), plus real Fab downloads listed in
``ANGELO_QA_FAB_SAMPLES`` (a JSON list of ``{path, format, title}``; local files only, never committed). The Fab
account, its browser and the dialog click are not exercised here: they need a signed-in Fab profile.
"""

