from angelo_agent import fab_formats as formats


def obj_text(vertices=3):
    return ('# made by a test\nmtllib chair.mtl\no Chair\n' + 'v 0 0 0\n' * vertices + 'f 1 2 3\n').encode()


class LabelTests(unittest.TestCase):
    def test_every_dialog_label_names_its_format(self):
        for label, code in (('FBX', 'fbx'), ('Blender', 'blend'), ('OBJ', 'obj'), ('GLTF', 'gltf'),
                            ('USD', 'usd'), ('Texture Set', 'surface'), ('glb', 'glb'), ('gltf', 'gltf'),
                            ('usdz', 'usd'), (' fbx ', 'fbx')):
            with self.subTest(label=label):
                self.assertEqual(formats.for_label(label).code, code)

    def test_engine_and_other_groups_are_not_formats(self):
        for label in ('Unreal Engine', 'Unity', 'Additional files', 'Converted Files', 'Maya', '3ds Max', '', None, 7):
            with self.subTest(label=label):
                self.assertIsNone(formats.for_label(label))

    def test_glb_is_the_only_direct_format_and_comes_first(self):
        self.assertEqual([row.code for row in formats.FORMATS if row.direct], ['glb'])
        self.assertEqual(formats.FORMATS[0].code, 'glb')
        self.assertEqual(formats.BY_CODE['surface'].kind, 'material')
        self.assertTrue(all(row.kind == 'model' for row in formats.FORMATS if row.code != 'surface'))


class SniffTests(unittest.TestCase):
    def test_model_and_image_magic(self):
        cases = {
            b'glTF\x02\x00\x00\x00': 'glb', b'Kaydara FBX Binary  \x00\x1a\x00\x00': 'fbx',
            b'BLENDER-v405RENDH': 'blend', b'PXR-USDC\x00': 'usdc', b'#usda 1.0\n': 'usda',
            b'\x89PNG\r\n\x1a\n': 'png', b'\xff\xd8\xff\xe0': 'jpeg', b'RIFF\x00\x00\x00\x00WEBPVP8 ': 'webp',
            b'v/1\x01\x02\x00\x00\x00': 'exr', b'II*\x00\x08': 'tiff', b'MM\x00*\x00': 'tiff',
            b'#?RADIANCE\n': 'hdr', b'{"asset": {"version": "2.0"}}': 'gltf', obj_text(): 'obj',
            b'newmtl Wood\nKd 0.8 0.6 0.4\nmap_Kd wood.jpg\n': 'mtl', b'just some notes\n': '',
        }
        for head, kind in cases.items():
            with self.subTest(kind=kind):
                self.assertEqual(formats.sniff(head, len(head)), kind)

    def test_zip_versus_usdz_is_read_from_the_first_member(self):
        def local(name):
            return b'PK\x03\x04' + b'\x00' * 22 + struct.pack('<HH', len(name), 0) + name
        self.assertEqual(formats.sniff(local(b'model.usdc')), 'usdz')
        self.assertEqual(formats.sniff(local(b'Chairs Pack.obj')), 'zip')

    def test_ascii_fbx_is_refused_with_a_reason(self):
        with self.assertRaises(formats.Unsupported) as refused:
            formats.sniff(b'; FBX 7.4.0 project file\n')
        self.assertIn('ASCII', str(refused.exception))
        self.assertEqual(formats.kind_of_content(b'; FBX 7.4.0 project file\n'), '')

    def test_compressed_blend_only_when_it_inflates_to_blender(self):
        self.assertEqual(formats.sniff(gzip.compress(b'BLENDER-v300' + b'\x00' * 64)), 'blend')
        self.assertEqual(formats.sniff(gzip.compress(b'hello world, not a blend file')), '')
        self.assertEqual(formats.sniff(b'\x28\xb5\x2f\xfd\x00'), 'blend')   # Zstandard: the converter confirms it.

    def test_tga_and_bmp_need_consistent_headers(self):
        tga = bytes([0, 0, 2]) + b'\x00' * 9 + struct.pack('<HH', 4, 4) + bytes([32, 8])
        self.assertEqual(formats.sniff(tga, 18 + 4 * 4 * 4), 'tga')
        self.assertEqual(formats.sniff(tga, None), '')
        self.assertEqual(formats.sniff(bytes([0, 0, 2]) + b'\x00' * 9 + struct.pack('<HH', 0, 4) + bytes([32, 0]),
                                       100), '')
        bmp = b'BM' + struct.pack('<I', 70) + b'\x00' * 30
        self.assertEqual(formats.sniff(bmp, 70), 'bmp')
        self.assertEqual(formats.sniff(bmp, 71), '')


class MemberTests(unittest.TestCase):
    def test_kept_members_are_the_format_its_sidecars_and_images(self):
        obj = formats.BY_CODE['obj']
        self.assertTrue(formats.keep_member(obj, 'obj'))
        self.assertTrue(formats.keep_member(obj, 'mtl'))
        self.assertTrue(formats.keep_member(obj, 'jpeg'))
        for other in ('fbx', 'zip', 'blend', ''):
            with self.subTest(kind=other):
                self.assertFalse(formats.keep_member(obj, other))
        # A glTF buffer has no signature to sniff: its model's URIs name it (test_native_fab_archive).
        self.assertTrue(formats.BY_CODE['gltf'].named_sidecars)
        self.assertFalse(any(row.named_sidecars for row in formats.FORMATS if row.code != 'gltf'))

    def test_level_of_detail_siblings_reduce_to_the_most_detailed(self):
        fbx = formats.BY_CODE['fbx']
        members = [('Rock_LOD2.fbx', 'fbx'), ('Rock_LOD0.fbx', 'fbx'), ('Rock_LOD1.fbx', 'fbx'),
                   ('Tree-lod1.fbx', 'fbx'), ('Tree-lod3.fbx', 'fbx'), ('Bench.fbx', 'fbx'), ('Bench_D.png', 'png')]
        self.assertEqual(formats.chosen_models(fbx, members), ['Bench.fbx', 'Rock_LOD0.fbx', 'Tree-lod1.fbx'])

    def test_a_pack_keeps_every_model_up_to_the_limit(self):
        fbx = formats.BY_CODE['fbx']
        members = [('pack/item_%02d.fbx' % i, 'fbx') for i in range(formats.MAX_MODELS)]
        self.assertEqual(len(formats.chosen_models(fbx, members)), formats.MAX_MODELS)
        with self.assertRaises(formats.Unsupported):
            formats.chosen_models(fbx, members + [('pack/one_more.fbx', 'fbx')])

    def test_no_model_of_the_format_is_refused(self):
        with self.assertRaises(formats.Unsupported) as refused:
            formats.chosen_models(formats.BY_CODE['blend'], [('readme.txt', ''), ('chair.fbx', 'fbx')])
        self.assertIn('.blend', str(refused.exception))


if __name__ == '__main__':
    unittest.main()
